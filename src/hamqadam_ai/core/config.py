#: Process-wide singleton. Configuration is immutable for the lifetime of a
#: process, so it is built once and shared. Guarded by a lock because the
#: FastAPI lifespan hook and a background janitor may race on first access.
_settings_singleton: Settings | None = None
_settings_lock = threading.Lock()


def get_settings() -> Settings:
    """Return the process-wide settings singleton, building it on first use.

    Raises:
        ConfigurationError: if the configuration fails validation. Pydantic's
            own ``ValidationError`` is wrapped so callers only ever have to
            catch :class:`~hamqadam_ai.core.exceptions.HamqadamError`.
    """
    global _settings_singleton
    if _settings_singleton is not None:
        return _settings_singleton
    with _settings_lock:
        if _settings_singleton is None:
            _settings_singleton = _build_settings()
    return _settings_singleton


def reload_settings(**overrides: Any) -> Settings:
    """Rebuild the singleton from disk, applying ``overrides`` at top precedence.

    Intended for tests and for the ``scripts/`` entry points, which need to
    point the service at a different config directory or flip one threshold
    without editing YAML.

    Args:
        **overrides: Init kwargs forwarded to :class:`Settings`; they outrank
            environment variables and every YAML layer.

    Returns:
        The freshly built settings object, which is also installed as the new
        process-wide singleton.
    """
    global _settings_singleton
    with _settings_lock:
        _settings_singleton = _build_settings(**overrides)
    return _settings_singleton


def _build_settings(**overrides: Any) -> Settings:
    """Instantiate :class:`Settings`, normalising validation failures."""
    try:
        return Settings(**overrides)
    except ConfigurationError:
        raise
    except ValidationError as exc:
        raise ConfigurationError(
            "Service configuration failed validation.",
            details={
                "errors": [
                    {
                        "location": ".".join(str(part) for part in error["loc"]),
                        "problem": error["msg"],
                    }
                    for error in exc.errors()
                ]
            },
            cause=exc,
        ) from exc


