class AlignmentConfig(BaseModel):
    """How a detected face is warped into the recogniser's input frame."""

    output_size: tuple[int, int] = (112, 112)
    max_alignment_residual: float = Field(default=0.28, gt=0.0, le=2.0)
    allow_box_fallback: bool = True
    box_fallback_margin: float = Field(default=0.10, ge=0.0, le=1.0)

    @field_validator("output_size")
    @classmethod
    def _matches_arcface(cls, value: tuple[int, int]) -> tuple[int, int]:
        """ArcFace's template is defined at 112x112 and is not resizable.

        The five reference landmark coordinates are absolute pixel positions in
        that frame, so changing the output size silently mis-places every one
        of them and quietly degrades recognition rather than failing.
        """
        if value != (112, 112):
            raise ValueError(
                "embedding.alignment.output_size must be [112, 112]: the ArcFace "
                "landmark template is defined in absolute pixels at that size."
            )
        return value


