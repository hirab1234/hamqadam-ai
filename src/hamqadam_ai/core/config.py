    strong_match_score: float = Field(default=75.0, gt=0.0, le=100.0)
    review_score: float = Field(default=50.0, gt=0.0, le=100.0)
    floor_similarity: float = Field(default=0.0, ge=-1.0, lt=1.0)

    @model_validator(mode="after")
    def _ordered(self) -> ScoreCalibration:
        if self.review_score >= self.strong_match_score:
            raise ValueError(
                "matching.calibration.review_score must be below strong_match_score"
            )
        return self


