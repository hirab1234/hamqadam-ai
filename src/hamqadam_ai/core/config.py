"""Layered, strongly-typed configuration.

Resolution order, later layers overriding earlier ones:

1. Field defaults declared on the models in this module.
2. Every ``*.yaml`` in the config directory (``app``, ``logging``, ``models``,
   ``thresholds``), deep-merged in that order.
3. ``app.<environment>.yaml`` if present, giving per-environment overlays.
4. A ``.env`` file, if one exists next to the repository root.
5. Process environment variables prefixed ``HQ_``, with ``__`` denoting
   nesting (``HQ_SERVER__PORT`` -> ``server.port``).

The config directory is ``$HQ_CONFIG_DIR`` when set, otherwise ``<repo>/configs``.

Every threshold that can change an accept/reject outcome is reachable from
:class:`Settings`; none is hard-coded elsewhere in the codebase.
"""

