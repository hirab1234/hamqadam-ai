class Settings(BaseSettings):
    """The complete, validated configuration of the AI verification service."""

    model_config = SettingsConfigDict(
        env_prefix="HQ_",
        env_nested_delimiter="__",
        env_file=str(REPO_ROOT / ".env"),
        env_file_encoding="utf-8",
        extra="ignore",
        case_sensitive=False,
        protected_namespaces=(),
        validate_default=True,
    )

    app: AppConfig = Field(default_factory=AppConfig)
    server: ServerConfig = Field(default_factory=ServerConfig)
    security: SecurityConfig = Field(default_factory=SecurityConfig)
    storage: StorageConfig = Field(default_factory=StorageConfig)
    runtime: RuntimeConfig = Field(default_factory=RuntimeConfig)
    observability: ObservabilityConfig = Field(default_factory=ObservabilityConfig)
    logging: LoggingConfig = Field(default_factory=LoggingConfig)

    model_store: ModelStoreConfig = Field(default_factory=ModelStoreConfig)
    models: dict[str, ModelSpec] = Field(default_factory=dict)
    execution_providers: dict[str, list[ProviderSpec]] = Field(default_factory=dict)

    detection: DetectionConfig = Field(default_factory=DetectionConfig)
    quality: QualityConfig = Field(default_factory=QualityConfig)
    embedding: EmbeddingConfig = Field(default_factory=EmbeddingConfig)
    matching: MatchingConfig = Field(default_factory=MatchingConfig)
    ocr: OcrConfig = Field(default_factory=OcrConfig)
    cnic_face: CnicFaceConfig = Field(default_factory=CnicFaceConfig)
    profile: ProfileAnalysisConfig = Field(
        default_factory=ProfileAnalysisConfig
    )
    duplicate: DuplicateConfig = Field(default_factory=DuplicateConfig)
    fraud: FraudConfig = Field(default_factory=FraudConfig)
    decision: DecisionConfig = Field(default_factory=DecisionConfig)

    #: Populated by the YAML source; useful in diagnostics and health output.
    config_dir_: str | None = Field(default=None, alias="_config_dir")

    # -- Source ordering ------------------------------------------------- #

    @classmethod
    def settings_customise_sources(
        cls,
        settings_cls: type[BaseSettings],
        init_settings: PydanticBaseSettingsSource,
        env_settings: PydanticBaseSettingsSource,
        dotenv_settings: PydanticBaseSettingsSource,
        file_secret_settings: PydanticBaseSettingsSource,
    ) -> tuple[PydanticBaseSettingsSource, ...]:
        """Highest precedence first: init kwargs > env > .env > YAML > secrets."""
        return (
            init_settings,
            env_settings,
            dotenv_settings,
            _YamlSettingsSource(settings_cls),
            file_secret_settings,
        )

    # -- Cross-section invariants ---------------------------------------- #

    @model_validator(mode="after")
    def _validate_production_hardening(self) -> Settings:
        """Refuse to serve production traffic with development-grade settings."""
        if not (self.app.is_production and self.security.enforce_production_hardening):
            return self

        problems: list[str] = []
        if self.app.debug:
            problems.append("app.debug must be false in production")
        if self.security.require_api_key and not self.security.api_keys:
            problems.append("security.api_keys is empty while require_api_key is true")
        if not self.security.require_api_key:
            problems.append("security.require_api_key must be true in production")
        if "*" in self.server.cors.allow_origins:
            problems.append("server.cors.allow_origins must not contain '*' in production")
        if self.logging.renderer != "json":
            problems.append("logging.renderer must be 'json' in production")
        if not self.logging.redaction.enabled:
            problems.append("logging.redaction.enabled must be true in production")
        if not self.model_store.verify_checksum:
            problems.append("model_store.verify_checksum must be true in production")

        if problems:
            raise ConfigurationError(
                "Production hardening checks failed.",
                details={"problems": problems},
            )
        return self

    @model_validator(mode="after")
    def _validate_detector_chain(self) -> Settings:
        """Every detector in the chain must resolve to a declared model."""
        known = {
            "scrfd": "face_detector_scrfd",
            "yolo": "face_detector_yolo",
            "opencv_dnn": "face_detector_opencv_dnn",
            "haar": "face_detector_haar",
        }
        unknown = [name for name in self.detection.fallback_chain if name not in known]
        if unknown:
            raise ConfigurationError(
                f"detection.fallback_chain references unknown detectors: {unknown}",
                details={"unknown": unknown, "supported": sorted(known)},
            )
        # `models` is empty when Settings is built without YAML (unit tests);
        # only enforce the cross-reference when a registry is actually present.
        if self.models:
            missing = [
                known[name]
                for name in self.detection.fallback_chain
                if known[name] not in self.models
            ]
            if missing:
                raise ConfigurationError(
                    f"detection.fallback_chain requires models absent from models.yaml: {missing}",
                    details={"missing": missing},
                )
        return self

    # -- Helpers ---------------------------------------------------------- #

    def model_spec(self, key: str) -> ModelSpec:
        """Return the :class:`ModelSpec` registered under ``key``.

        Raises:
            ConfigurationError: if no such model is declared.
        """
        try:
            return self.models[key]
        except KeyError as exc:
            raise ConfigurationError(
                f"No model named {key!r} is declared in models.yaml.",
                details={"requested": key, "available": sorted(self.models)},
            ) from exc

    def providers_for(self, device: str) -> Sequence[ProviderSpec]:
        """Return the execution-provider preference list for a device family."""
        return self.execution_providers.get(
            device, [ProviderSpec(name="CPUExecutionProvider")]
        )

    def model_version_map(self) -> dict[str, str]:
        """Map of model key to version string, for the API's ``model_versions``."""
        return {key: spec.version for key, spec in self.models.items() if spec.enabled}


