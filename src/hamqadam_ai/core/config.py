#: Repository root: src/hamqadam_ai/core/config.py -> up four levels.
REPO_ROOT: Path = Path(__file__).resolve().parents[3]

#: YAML files merged, in order, to form the base configuration.
#: ``model_digests.lock.yaml`` is generated by ``scripts/download_models.py``
#: and merged *after* ``models.yaml`` so the pinned SHA-256 digests it records
#: override the ``null`` placeholders in the declaration file.
_CONFIG_FILE_ORDER: tuple[str, ...] = (
    "app.yaml",
    "logging.yaml",
    "models.yaml",
    "model_digests.lock.yaml",
    "thresholds.yaml",
)

DeviceLiteral = Literal["auto", "cpu", "cuda", "tensorrt", "directml", "coreml"]
EnvironmentLiteral = Literal["development", "testing", "staging", "production"]
LogLevelLiteral = Literal["DEBUG", "INFO", "WARNING", "ERROR", "CRITICAL"]


def _deep_merge(base: dict[str, Any], overlay: Mapping[str, Any]) -> dict[str, Any]:
    """Recursively merge ``overlay`` into ``base``, returning a new dict.

    Mappings merge key-by-key; every other type (including lists) is replaced
    wholesale. Replacing lists rather than concatenating them is deliberate:
    an operator overriding ``fallback_chain`` means "use exactly this chain".
    """
    merged = dict(base)
    for key, value in overlay.items():
        existing = merged.get(key)
        if isinstance(existing, dict) and isinstance(value, Mapping):
            merged[key] = _deep_merge(existing, value)
        else:
            merged[key] = value
    return merged


def resolve_config_dir() -> Path:
    """Return the directory holding the YAML configuration files."""
    override = os.environ.get("HQ_CONFIG_DIR")
    if override:
        path = Path(override).expanduser().resolve()
        if not path.is_dir():
            raise ConfigurationError(
                f"HQ_CONFIG_DIR points at {path} which is not a directory.",
                details={"config_dir": str(path)},
            )
        return path
    return REPO_ROOT / "configs"


class _YamlSettingsSource(PydanticBaseSettingsSource):
    """Settings source that deep-merges the project's YAML configuration."""

    def __init__(self, settings_cls: type[BaseSettings]) -> None:
        super().__init__(settings_cls)
        self._data: dict[str, Any] = self._load()

    def _load(self) -> dict[str, Any]:
        config_dir = resolve_config_dir()
        merged: dict[str, Any] = {}

        for filename in _CONFIG_FILE_ORDER:
            path = config_dir / filename
            if not path.is_file():
                continue
            merged = _deep_merge(merged, _read_yaml(path))

        # Environment overlay. The environment name itself may come from the
        # process environment, so it is read directly rather than from the
        # partially-built settings object.
        environment = (
            os.environ.get("HQ_APP__ENVIRONMENT")
            or str(merged.get("app", {}).get("environment", "development"))
        ).strip().lower()

        overlay = config_dir / f"app.{environment}.yaml"
        if overlay.is_file():
            merged = _deep_merge(merged, _read_yaml(overlay))

        merged["_config_dir"] = str(config_dir)
        return merged

    def get_field_value(  # pragma: no cover - required by the ABC
        self,
        field: Any,  # noqa: ARG002 - part of the PydanticBaseSettingsSource contract
        field_name: str,
    ) -> tuple[Any, str, bool]:
        return self._data.get(field_name), field_name, False

    def __call__(self) -> dict[str, Any]:
        return self._data


def _read_yaml(path: Path) -> dict[str, Any]:
    """Parse a YAML document, raising a typed error on malformed content."""
    try:
        with path.open("r", encoding="utf-8") as handle:
            loaded = yaml.safe_load(handle)
    except yaml.YAMLError as exc:
        raise ConfigurationError(
            f"Configuration file {path.name} is not valid YAML.",
            details={"path": str(path), "reason": str(exc)},
            cause=exc,
        ) from exc
    if loaded is None:
        return {}
    if not isinstance(loaded, dict):
        raise ConfigurationError(
            f"Configuration file {path.name} must contain a mapping at the top level.",
            details={"path": str(path), "top_level_type": type(loaded).__name__},
        )
    return loaded


