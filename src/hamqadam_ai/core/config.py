def _normalised_weights(weights: dict[str, float], label: str) -> dict[str, float]:
    """Rescale a weight mapping to sum to 1.0.

    Normalising rather than rejecting means an operator can raise one weight
    without having to rebalance every other by hand - the single most common
    way a hand-edited threshold file ends up subtly wrong.
    """
    total = sum(weights.values())
    if total <= 0:
        raise ValueError(f"{label} weights must sum to a positive value")
    if abs(total - 1.0) <= 1e-6:
        return weights
    return {key: value / total for key, value in weights.items()}


class RampMapping(BaseModel):
    """Maps a raw measurement onto ``[0, 1]`` through two anchor points.

    ``floor`` scores 0 and ``good`` scores 1, with a smoothstep in between.
    A smoothstep rather than a straight line because the derivative vanishes at
    both anchors, so a measurement sitting near an anchor does not swing the
    composite score on sensor noise alone.

    When ``floor > good`` the metric is lower-is-better - noise sigma, JPEG
    blockiness, chromatic aberration - and the ramp inverts automatically.

    ``log_scale`` interpolates in log10 space instead. This is not a cosmetic
    choice: the focus measures span three orders of magnitude between a sharp
    photograph and an unusable one (measured Laplacian variance runs 37 to
    10,014 on the same portrait), and a linear ramp across that range spends
    almost its entire output on the top decade while collapsing everything
    below it to zero. Perceptually and statistically these quantities are
    log-distributed, so the ramp should be too.
    """

    floor: float
    good: float
    log_scale: bool = False

    @property
    def lower_is_better(self) -> bool:
        """True when a smaller raw value scores higher."""
        return self.floor > self.good

    @model_validator(mode="after")
    def _anchors_valid(self) -> RampMapping:
        if self.floor == self.good:
            raise ValueError("ramp mapping anchors `floor` and `good` must differ")
        if self.log_scale and (self.floor <= 0.0 or self.good <= 0.0):
            raise ValueError(
                "log_scale ramp anchors must both be strictly positive"
            )
        return self


class BandMapping(BaseModel):
    """Maps a raw measurement onto ``[0, 1]`` where both extremes are bad.

    Zero outside ``[min_acceptable, max_acceptable]``, one across the
    ``[ideal_low, ideal_high]`` plateau, smoothstep on the two shoulders.

    The plateau matters: an image at mean luminance 120 and one at 160 are both
    simply well exposed, and ramping to a single ideal point would penalise one
    of them for no reason a photographer would recognise.
    """

    min_acceptable: float
    ideal_low: float
    ideal_high: float
    max_acceptable: float

    @model_validator(mode="after")
    def _ordered(self) -> BandMapping:
        bounds = (
            self.min_acceptable,
            self.ideal_low,
            self.ideal_high,
            self.max_acceptable,
        )
        if list(bounds) != sorted(bounds):
            raise ValueError(
                "band mapping requires "
                "min_acceptable <= ideal_low <= ideal_high <= max_acceptable"
            )
        return self


class QualityAggregationConfig(BaseModel):
    """How the component scores combine into the composite."""

    #: Power-mean exponent. 1.0 is the arithmetic mean; below 1.0 penalises low
    #: components progressively harder, so one catastrophic metric cannot be
    #: averaged away by five healthy ones.
    power: float = Field(default=0.5, gt=0.0, le=2.0)
    weights: dict[str, float] = Field(
        default_factory=lambda: {
            "blur": 0.22,
            "sharpness": 0.16,
            "brightness": 0.12,
            "contrast": 0.10,
            "noise": 0.11,
            "resolution": 0.16,
            "pixelation": 0.09,
            "distortion": 0.04,
        }
    )
    critical_floor: float = Field(default=0.12, ge=0.0, le=1.0)
    critical_components: list[str] = Field(
        default_factory=lambda: ["blur", "sharpness", "resolution"]
    )

    _COMPONENTS = (
        "blur",
        "sharpness",
        "brightness",
        "contrast",
        "noise",
        "resolution",
        "pixelation",
        "distortion",
    )

    @model_validator(mode="after")
    def _validate(self) -> QualityAggregationConfig:
        missing = [key for key in self._COMPONENTS if key not in self.weights]
        if missing:
            raise ValueError(f"quality.aggregation.weights is missing keys: {missing}")
        unknown = [key for key in self.weights if key not in self._COMPONENTS]
        if unknown:
            raise ValueError(
                f"quality.aggregation.weights has unknown keys: {unknown}"
            )
        bad_critical = [
            key for key in self.critical_components if key not in self._COMPONENTS
        ]
        if bad_critical:
            raise ValueError(
                f"quality.aggregation.critical_components has unknown keys: "
                f"{bad_critical}"
            )
        object.__setattr__(
            self, "weights", _normalised_weights(self.weights, "quality.aggregation")
        )
        return self


class RoleQualityConfig(BaseModel):
    """Per-image-role quality acceptance policy."""

    min_overall: float = Field(ge=0.0, le=100.0)

    #: Components whose critical floor is enforced *for this role*, overriding
    #: ``aggregation.critical_components``. ``None`` inherits the global list.
    #:
    #: Exists because the global list is role-blind in a way that measurement
    #: showed to be wrong. The critical floor on focus assumes softness means
    #: camera shake, which is right for a live capture. For a portrait printed
    #: at a few hundred dpi, softness is the physics of the medium: measured on
    #: a print-degraded reference face, sharpness fell to 0.00 while ArcFace
    #: still separated the same person at cosine 0.551 from an impostor at
    #: -0.028, against a CNIC threshold of 0.42. Refusing to compare that image
    #: would discard a decisive match on the grounds that it looked like what
    #: it is.
    critical_components: list[str] | None = None


