class SecurityConfig(BaseModel):
    """Authentication, authorisation and abuse controls."""

    api_key_header: str = "X-API-Key"
    api_keys: Annotated[list[str], NoDecode] = Field(default_factory=list)
    require_api_key: bool = True
    hmac: HmacConfig = Field(default_factory=HmacConfig)
    rate_limit: RateLimitConfig = Field(default_factory=RateLimitConfig)
    enforce_production_hardening: bool = True

    @field_validator("api_keys", mode="before")
    @classmethod
    def _split_csv(cls, value: Any) -> Any:
        """Accept a comma-separated string so ``HQ_SECURITY__API_KEYS`` works.

        ``NoDecode`` on the annotation is what makes this reachable from the
        environment. Without it pydantic-settings classifies ``list[str]`` as a
        complex field and calls ``json.loads`` inside the *source*, so::

            HQ_SECURITY__API_KEYS=my-secret-key

        failed with ``SettingsError: error parsing value for field "security"``
        before this validator ran - an error naming the whole section rather
        than the field, and mentioning nothing about the real requirement, which
        was JSON. Environment variables are strings and an operator setting one
        key will write it plainly, so refusing that is a trap laid squarely in
        the deployment path.

        A JSON array is still accepted, since it arrives here as a string that
        happens to start with ``[``.
        """
        if isinstance(value, str):
            text = value.strip()
            if text.startswith("["):
                try:
                    parsed = json.loads(text)
                except ValueError as exc:
                    raise ValueError(
                        "security.api_keys looks like a JSON array but is not "
                        "valid JSON. Use a comma-separated list instead, or fix "
                        "the quoting."
                    ) from exc
                if not isinstance(parsed, list):
                    raise ValueError("security.api_keys must be a list of keys.")
                return [str(item).strip() for item in parsed if str(item).strip()]
            return [item.strip() for item in text.split(",") if item.strip()]
        return value


