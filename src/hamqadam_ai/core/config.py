class OcclusionConfig(BaseModel):
    """Occlusion analyser thresholds and per-region importance weights."""

    region_threshold: float = Field(default=0.55, ge=0.0, le=1.0)
    overall_threshold: float = Field(default=0.45, ge=0.0, le=1.0)
    region_weights: dict[str, float] = Field(
        default_factory=lambda: {
            "forehead": 0.10,
            "left_eye": 0.22,
            "right_eye": 0.22,
            "nose": 0.18,
            "mouth": 0.16,
            "chin": 0.12,
        }
    )
    texture_energy_floor: float = Field(default=0.35, ge=0.0, le=1.0)
    skin_coverage_floor: float = Field(default=0.30, ge=0.0, le=1.0)
    symmetry_delta_threshold: float = Field(default=0.35, ge=0.0, le=1.0)
    visibility_weight: float = Field(default=0.35, ge=0.0, le=1.0)

    @model_validator(mode="after")
    def _weights_normalised(self) -> OcclusionConfig:
        total = sum(self.region_weights.values())
        if total <= 0:
            raise ValueError("detection.occlusion.region_weights must sum to a positive value")
        if abs(total - 1.0) > 1e-6:
            # Normalise rather than reject: an operator tuning one region up
            # should not have to rebalance the other five by hand.
            object.__setattr__(
                self,
                "region_weights",
                {key: value / total for key, value in self.region_weights.items()},
            )
        return self


